                    lootBin.lootBinSkin.ToString(CultureInfo.InvariantCulture) + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendJumpPads(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            var jumpPads = world.Where(o => o.customType == "jump-pad").ToList();
            if (!live && jumpPads.Count > 0) { code.AppendLine(); code.AppendLine("\t// Jump pads"); }
            foreach (var jumpPad in jumpPads)
            {
                if (!Nearly(jumpPad.scale.x, jumpPad.scale.y) || !Nearly(jumpPad.scale.x, jumpPad.scale.z))
                    throw new ArgumentException(L.F("#ARG0_APEX_PROPS_SUPPORT_UNIFORM", jumpPad.displayName));
                string expression = "ReMap_CreateJumpPad( " +
                    Position(jumpPad.position, originOffset, symbolicOffset) + ", " +
                    Vector(ApexDisplay.Angles(WorldView.ToVector(jumpPad.rotation))) + ", " +
                    (jumpPad.allowMantle ? "true" : "false") + ", " +
                    Number(jumpPad.fadeDistance) + ", " +
                    jumpPad.realmId.ToString(CultureInfo.InvariantCulture) + ", " +
                    Number(jumpPad.scale.x) + ", " + Number(jumpPad.jumpPadLaunchVelocity) + ", " +
                    Number(jumpPad.jumpPadForwardScale) + ", " + Number(jumpPad.jumpPadRadius) + ", " +
                    (jumpPad.jumpPadDoubleJump ? "true" : "false") + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendSpawnPoints(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            var spawnPoints = world.Where(o => o.customType == "spawn-point").ToList();
            if (!live && spawnPoints.Count > 0) { code.AppendLine(); code.AppendLine("\t// Player spawn points"); }
            foreach (var spawnPoint in spawnPoints)
            {
                string expression = "ReMap_CreateSpawnPoint( " +
                    Position(spawnPoint.position, originOffset, symbolicOffset) + ", " +
                    Vector(ApexDisplay.Angles(WorldView.ToVector(spawnPoint.rotation))) + ", " +
                    spawnPoint.spawnPointTeam.ToString(CultureInfo.InvariantCulture) + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendTriggers(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            if (live) return;
            var triggers = world.Where(o => o.customType == "trigger").ToList();
            if (triggers.Count == 0) return;
            code.AppendLine(); code.AppendLine("\t// Triggers");
            for (int index = 0; index < triggers.Count; index++)
            {
                var trigger = triggers[index];
                string variable = "remapTrigger" + index.ToString(CultureInfo.InvariantCulture);
                code.Append("\tentity ").Append(variable).Append(" = ReMap_CreateTrigger( ")
                    .Append(Position(trigger.position, originOffset, symbolicOffset)).Append(", ")
                    .Append(Vector(ApexDisplay.Angles(WorldView.ToVector(trigger.rotation)))).Append(", ")
                    .Append(Number(trigger.triggerRadius)).Append(", ")
                    .Append(Number(trigger.triggerHalfHeight)).Append(", ")
                    .Append(trigger.triggerDebug ? "true" : "false").Append(", ")
                    .Append(trigger.realmId.ToString(CultureInfo.InvariantCulture)).AppendLine(" )");
                AppendTriggerCallback(code, variable, "SetEnterCallback", trigger.triggerEnterCallback);
                AppendTriggerCallback(code, variable, "SetLeaveCallback", trigger.triggerLeaveCallback);
                code.Append("\tDispatchSpawn( ").Append(variable).AppendLine(" )");
            }
        }

        private static void AppendJumpTowers(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            var towers = world.Where(o => o.customType == "jump-tower").ToList();
            if (!live && towers.Count > 0) { code.AppendLine(); code.AppendLine("\t// Jump towers"); }
            foreach (var tower in towers)
            {
                string expression = "ReMap_CreateJumpTower( " +
                    Position(tower.position, originOffset, symbolicOffset) + ", " +
                    Vector(ApexDisplay.Angles(WorldView.ToVector(tower.rotation))) + ", " +
                    Number(tower.jumpTowerHeight) + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendTriggerCallback(StringBuilder code, string variable,
            string setter, string callback)
        {
            callback = (callback ?? "").Replace("\r\n", "\n").Replace('\r', '\n');
            if (string.IsNullOrWhiteSpace(callback)) return;
            code.Append('\t').Append(variable).Append('.').Append(setter)
                .AppendLine("( void function( entity trigger, entity ent )");
            code.AppendLine("\t{");
            foreach (string line in callback.Split('\n')) code.Append("\t\t").AppendLine(line);
            code.AppendLine("\t} )");
        }

        private static Vector3 OriginOffset(MapDocument document)
        {
            if (!document.originOffset.IsFinite || !ApexCoordinates.ContainsUnity(document.originOffset))
                throw new ArgumentException(L.T("#SCENE") + " : " + ApexCoordinates.LimitMessage);
            return WorldView.ToVector(document.originOffset);
        }

        private static bool HasOriginOffset(Vector3 value) => value.x != 0f || value.y != 0f || value.z != 0f;

        private static string Position(Float3 localPosition, Vector3 originOffset, bool symbolicOffset)
        {
            Vector3 local = WorldView.ToVector(localPosition);
            Vector3 game = local + originOffset;
            if (!ApexCoordinates.ContainsUnity(WorldView.ToData(game))) throw new ArgumentException(ApexCoordinates.LimitMessage);
            return Vector(ApexDisplay.Position(symbolicOffset ? local : game)) + (symbolicOffset ? " + originOffset" : "");
        }

        private static string Vector(Vector3 value) => "<" + Number(value.x) + ", " + Number(value.y) + ", " + Number(value.z) + ">";
        private static string Number(float value)
        {
            double rounded = Math.Round(value, 4, MidpointRounding.AwayFromZero);
            if (Math.Abs(rounded) < 0.00005) rounded = 0;
            return rounded.ToString("0.####", CultureInfo.InvariantCulture);
        }
        private static bool Nearly(float a, float b) => Math.Abs(a - b) <= Math.Max(0.0001f, Math.Max(Math.Abs(a), Math.Abs(b)) * 0.0001f);
    }

