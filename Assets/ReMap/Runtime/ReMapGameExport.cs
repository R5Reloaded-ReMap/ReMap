        }

        private static MatchCollection FunctionMatches(string source, string functionName)
        {
            return Regex.Matches(source, @"(?m)^(?<indent>[ \t]*)void\s+function\s+" + Regex.Escape(functionName) + @"\s*\(\s*\)\s*\{");
        }

        private static bool TryFunctionBody(string source, string functionName, string path, out string body)
        {
            MatchCollection matches = FunctionMatches(source, functionName);
            if (matches.Count != 1) { body = ""; return false; }
            Match match = matches[0];
            int open = match.Index + match.Value.LastIndexOf('{');
            int close = FindClosingBrace(source, open, path, functionName);
            body = source.Substring(open + 1, close - open - 1).Trim('\r', '\n');
            return true;
        }

        private static string SetManagedPaks(string source, IEnumerable<string> rpaks, string path)
        {
            string newline = source.Contains("\r\n") ? "\r\n" : "\n";
            string withoutManaged = RemoveManagedPaks(source, path);
            string[] archives = (rpaks ?? Array.Empty<string>())
                .Where(rpak => !Regex.IsMatch(withoutManaged,
                    "(?im)^[ \\t]*\"" + Regex.Escape(rpak) + "\"[ \\t]+\"[012]\"[ \\t]*(?://.*)?$"))
                .ToArray();
            if (archives.Length == 0) return withoutManaged;

            Match pakList = Regex.Match(withoutManaged,
                "(?m)^(?<indent>[ \\t]*)\"PakList\"[ \\t]*\\r?$[ \\t]*\\n(?<open>[ \\t]*)\\{");
            if (pakList.Success)
            {
                int open = pakList.Index + pakList.Value.LastIndexOf('{');
                int close = FindClosingBrace(withoutManaged, open, path, "PakList");
                int closeLine = withoutManaged.LastIndexOf('\n', close);
                closeLine = closeLine < 0 ? close : closeLine + 1;
                string indent = pakList.Groups["open"].Value + "    ";
                string block = ManagedPakBlock(indent, archives, newline);
                string prefix = withoutManaged.Substring(0, closeLine).TrimEnd('\r', '\n');
                return prefix + newline + block + newline + withoutManaged.Substring(closeLine);
            }

            Match levelSet = Regex.Match(withoutManaged,
                "(?m)^(?<indent>[ \\t]*)\"LevelSet\"[ \\t]*\\r?$[ \\t]*\\n(?<open>[ \\t]*)\\{");
            if (!levelSet.Success)
                throw new InvalidDataException(path + " must contain a LevelSet block.");
            int levelOpen = levelSet.Index + levelSet.Value.LastIndexOf('{');
            int levelClose = FindClosingBrace(withoutManaged, levelOpen, path, "LevelSet");
            int levelCloseLine = withoutManaged.LastIndexOf('\n', levelClose);
            levelCloseLine = levelCloseLine < 0 ? levelClose : levelCloseLine + 1;
            string childIndent = levelSet.Groups["open"].Value + "    ";
            string entryIndent = childIndent + "    ";
            string newPakList = childIndent + "\"PakList\"" + newline + childIndent + "{" + newline +
                ManagedPakBlock(entryIndent, archives, newline) + newline + childIndent + "}";
            string levelPrefix = withoutManaged.Substring(0, levelCloseLine).TrimEnd('\r', '\n');
            return levelPrefix + newline + newPakList + newline + withoutManaged.Substring(levelCloseLine);
        }

        private static string ManagedPakBlock(string indent, IEnumerable<string> rpaks, string newline)
        {
            var result = new StringBuilder();
            result.Append(indent).Append(ManagedPaksBegin);
            foreach (string rpak in rpaks)
                result.Append(newline).Append(indent).Append('"').Append(rpak).Append("\" \"2\"");
            result.Append(newline).Append(indent).Append(ManagedPaksEnd);
            return result.ToString();
        }

        private static string RemoveManagedPaks(string source, string path)
        {
            int begin = source.IndexOf(ManagedPaksBegin, StringComparison.Ordinal);
            int end = source.IndexOf(ManagedPaksEnd, StringComparison.Ordinal);
            if (begin < 0 && end < 0) return source;
            if (begin < 0 || end < begin || source.IndexOf(ManagedPaksBegin,
                    begin + ManagedPaksBegin.Length, StringComparison.Ordinal) >= 0 ||
                source.IndexOf(ManagedPaksEnd, end + ManagedPaksEnd.Length,
                    StringComparison.Ordinal) >= 0)
                throw new InvalidDataException(path + " contains an invalid ReMap managed paks block.");
            int lineStart = source.LastIndexOf('\n', begin);
            lineStart = lineStart < 0 ? 0 : lineStart + 1;
            int lineEnd = source.IndexOf('\n', end + ManagedPaksEnd.Length);
            if (lineEnd < 0) lineEnd = source.Length;
            else lineEnd++;
            return source.Remove(lineStart, lineEnd - lineStart);
        }

        private static string ReplaceFunctionBody(string source, string functionName, string body, string path)
        {
            MatchCollection matches = FunctionMatches(source, functionName);
            if (matches.Count != 1)
                throw new InvalidDataException(path + " must contain exactly one " + functionName + "() function.");
            Match match = matches[0];
            int open = match.Index + match.Value.LastIndexOf('{');
            int close = FindClosingBrace(source, open, path, functionName);
            string newline = source.Contains("\r\n") ? "\r\n" : "\n";
            string indent = match.Groups["indent"].Value;
            string normalized = (body ?? "").Replace("\r\n", "\n").TrimEnd();
            string signature = indent + "void function " + functionName + "()";
            string formatted = normalized.Length == 0 ? "" : string.Join(newline, normalized.Split('\n').Select(line => indent + line)) + newline;
            string replacement = normalized.Length == 0 ? signature + " {}" : signature + newline + indent + "{" + newline + formatted + indent + "}";
            return source.Substring(0, match.Index) + replacement + source.Substring(close + 1);
        }

        private static int FindClosingBrace(string source, int openingBrace, string path, string functionName)
        {
            int depth = 0;
            bool lineComment = false, blockComment = false, escaped = false;
            char quote = '\0';
            for (int i = openingBrace; i < source.Length; i++)
            {
                char current = source[i];
                char next = i + 1 < source.Length ? source[i + 1] : '\0';
                if (lineComment) { if (current == '\n') lineComment = false; continue; }
                if (blockComment) { if (current == '*' && next == '/') { blockComment = false; i++; } continue; }
                if (quote != '\0')
                {
                    if (escaped) { escaped = false; continue; }
                    if (current == '\\') { escaped = true; continue; }
                    if (current == quote) quote = '\0';
                    continue;
                }
                if (current == '/' && next == '/') { lineComment = true; i++; continue; }
                if (current == '/' && next == '*') { blockComment = true; i++; continue; }
                if (current == '"' || current == '\'') { quote = current; continue; }
                if (current == '{') depth++;
                else if (current == '}' && --depth == 0) return i;
            }
            throw new InvalidDataException(path + " contains an unclosed " + functionName + "() function.");
        }

        private static string SetLoadMap(string source, bool enabled, string path)
        {
            var matches = Regex.Matches(source, @"(?m)^(?<prefix>[ \t]*global\s+const\s+bool\s+REMAP_LOAD_MAP\s*=\s*)(?:true|false)(?<suffix>[ \t]*)$");
            if (matches.Count != 1)
                throw new InvalidDataException(path + " must contain exactly one REMAP_LOAD_MAP boolean constant.");
            Match match = matches[0];
            string replacement = match.Groups["prefix"].Value + (enabled ? "true" : "false") + match.Groups["suffix"].Value;
            return source.Substring(0, match.Index) + replacement + source.Substring(match.Index + match.Length);
        }

        private static void BackupOnce(string path)
        {
            string backup = path + ".remap.bak";
            if (File.Exists(path) && !File.Exists(backup)) File.Copy(path, backup);
        }
    }

    internal static class ReMapNetConsole
    {
        internal static int Send(string gameTarget, string platformDirectory, string address, string key, string password, IEnumerable<string> sourceCommands)
        {
            var commands = (sourceCommands ?? Enumerable.Empty<string>()).SelectMany(command => (command ?? "").Split(new[] { "\r\n", "\n" }, StringSplitOptions.RemoveEmptyEntries)).Select(command => command.Trim()).Where(command => command.Length > 0).ToArray();
            if (commands.Length == 0) throw new ArgumentException(L.T("#ENTER_COMMAND_SEND"));
            key = (key ?? "").Trim(); password = password ?? "";
            if (GameTargets.Normalize(gameTarget) == GameTargets.R5Flowstate && key.Length == 0 && password.Length == 0)
                return ReMapLiveBridge.Send(commands);
            if (key.Length == 0 || password.Length == 0)
                throw new InvalidOperationException(L.T("#CONFIGURE_RCON_AES_KEY_PASSWORD"));

            string platform = (platformDirectory ?? "").Trim();
            if (string.IsNullOrWhiteSpace(platform)) throw new DirectoryNotFoundException(L.T("#CONFIGURE_PLATFORM_FOLDER_SETTINGS_FIRST"));
            string netcon = Path.GetFullPath(Path.Combine(platform, "..", "bin", "netcon.exe"));
            if (!File.Exists(netcon)) throw new FileNotFoundException(L.T("#R5RELOADED_NETCON_EXE_FOUND_NEXT"), netcon);
            address = (address ?? "").Trim();
            if (address.Length == 0 || address.Length > 128 || address.Any(c => !(char.IsLetterOrDigit(c) || "[]:.-_%".Contains(c))))
                throw new ArgumentException(L.T("#ENTER_VALID_RCON_SERVER_ADDRESS"));
            byte[] decoded;
            try { decoded = Convert.FromBase64String(key); }
            catch (FormatException) { throw new ArgumentException(L.T("#RCON_AES_KEY_VALID_BASE64")); }
            if (decoded.Length != 16) throw new ArgumentException(L.T("#RCON_AES_KEY_CONTAIN_EXACTLY"));
            if (string.IsNullOrEmpty(password) || password.IndexOfAny(new[] { '\r', '\n' }) >= 0)
                throw new ArgumentException(L.T("#CONFIGURE_NON_EMPTY_RCON_PASSWORD"));
            var output = new StringBuilder(); object outputLock = new object();
            using (var process = new System.Diagnostics.Process())
            {
                process.StartInfo = new System.Diagnostics.ProcessStartInfo
                {
                    FileName = netcon,
                    Arguments = QuoteArgument(address) + " " + QuoteArgument(key),
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    RedirectStandardInput = true,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true
                };
                process.OutputDataReceived += (_, e) => { if (e.Data != null) lock (outputLock) output.AppendLine(e.Data); };
                process.ErrorDataReceived += (_, e) => { if (e.Data != null) lock (outputLock) output.AppendLine(e.Data); };
                if (!process.Start()) throw new InvalidOperationException(L.T("#COULD_START_R5RELOADED_NETCON_EXE"));
                process.BeginOutputReadLine(); process.BeginErrorReadLine();
                process.StandardInput.WriteLine("PASS " + password);
                foreach (string command in commands) process.StandardInput.WriteLine(command);
                process.StandardInput.Close();
                int timeout = Math.Min(45000, 10000 + commands.Length * 15);
                if (!process.WaitForExit(timeout))
                {
                    try { process.Kill(); } catch { }
                    throw new TimeoutException(L.T("#LIVE_GAME_CONNECTION_DID_FINISH"));
                }
                process.WaitForExit();
                string transcript; lock (outputLock) transcript = output.ToString();
                if (process.ExitCode != 0 || transcript.IndexOf("Authentication failed", StringComparison.OrdinalIgnoreCase) >= 0 || transcript.IndexOf("Failed to authenticate", StringComparison.OrdinalIgnoreCase) >= 0)
                    throw new InvalidOperationException(L.T("#RCON_REJECTED_CONNECTION_CHECK_ADDRESS"));
            }
            return commands.Length;
        }

        private static string QuoteArgument(string value) => "\"" + value.Replace("\"", "\\\"") + "\"";
    }

