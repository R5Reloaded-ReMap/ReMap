        private void ClampCodePreviewWindow(float width = -1, float height = -1)
        {
            if (codeWindow == null || root == null) return;
            float rootWidth = root.resolvedStyle.width, rootHeight = root.resolvedStyle.height;
            if (width < 0) width = codeWindow.resolvedStyle.width;
            if (height < 0) height = codeWindow.resolvedStyle.height;
            if (!float.IsFinite(rootWidth) || !float.IsFinite(rootHeight) || !float.IsFinite(width) || !float.IsFinite(height)) return;
            float maxWidth = Mathf.Max(1, rootWidth - 16), maxHeight = Mathf.Max(1, rootHeight - 16);
            width = Mathf.Clamp(width, Mathf.Min(680, maxWidth), maxWidth);
            height = Mathf.Clamp(height, Mathf.Min(260, maxHeight), maxHeight);
            codeWindow.style.width = width; codeWindow.style.height = height;
            float left = codeWindow.resolvedStyle.left, top = codeWindow.resolvedStyle.top;
            if (!float.IsFinite(left)) left = (rootWidth - width) * .5f;
            if (!float.IsFinite(top)) top = (rootHeight - height) * .5f;
            codeWindow.style.left = Mathf.Clamp(left, 8, Mathf.Max(8, rootWidth - width - 8));
            codeWindow.style.top = Mathf.Clamp(top, 8, Mathf.Max(8, rootHeight - height - 8));
        }

        private void BindCodePreviewResize(VisualElement handle)
        {
            Vector2 pointerStart = default, sizeStart = default; int pointerId = -1; bool resizing = false;
            handle.RegisterCallback<PointerDownEvent>(e =>
            {
                if (e.button != 0) return;
                if (e.clickCount == 2) { ResizeCodePreviewWindow(720, 520); e.StopPropagation(); return; }
                pointerStart = e.position; sizeStart = codeWindow.worldBound.size; pointerId = e.pointerId; resizing = true;
                handle.CapturePointer(pointerId); handle.AddToClassList("resizing"); codeWindow.BringToFront(); e.StopPropagation();
            });
            handle.RegisterCallback<PointerMoveEvent>(e =>
            {
                if (!resizing || e.pointerId != pointerId) return;
                Vector2 delta = (Vector2)e.position - pointerStart;
                ResizeCodePreviewWindow(sizeStart.x + delta.x, sizeStart.y + delta.y); e.StopPropagation();
            });
            void End()
            {
                if (!resizing) return; resizing = false; handle.RemoveFromClassList("resizing");
                if (handle.HasPointerCapture(pointerId)) handle.ReleasePointer(pointerId);
                pointerId = -1;
            }
            handle.RegisterCallback<PointerUpEvent>(e => { if (e.pointerId == pointerId) { End(); e.StopPropagation(); } });
            handle.RegisterCallback<PointerCaptureOutEvent>(_ => End());
        }

        private void ResizeCodePreviewWindow(float width, float height)
        {
            float rootWidth = root.resolvedStyle.width, rootHeight = root.resolvedStyle.height;
            float left = Mathf.Max(8, codeWindow.resolvedStyle.left), top = Mathf.Max(8, codeWindow.resolvedStyle.top);
            float maxWidth = Mathf.Max(1, rootWidth - left - 8), maxHeight = Mathf.Max(1, rootHeight - top - 8);
            width = Mathf.Clamp(width, Mathf.Min(680, maxWidth), maxWidth);
            height = Mathf.Clamp(height, Mathf.Min(260, maxHeight), maxHeight);
            codePreviewWidth = width; codePreviewHeight = height;
            codeWindow.style.width = width; codeWindow.style.height = height;
            ClampCodePreviewWindow(width, height);
        }

