        private void BuildScriptProperties(MapObject item, VisualElement section)
        {
            var properties = item.scriptProperties ?? new List<ScriptProperty>();
            var propertiesSection = new VisualElement { name = "script-properties" }; propertiesSection.AddToClassList("inspector-subsection");
            propertiesSection.tooltip = L.T("#CHOOSE_PROPERTY_FAMILY_COMPATIBLE_FIELD");
