        private void BuildClassicPropSettings(MapObject item, VisualElement section)
        {
            var settings = new VisualElement { name = "classic-prop-settings" };
            settings.AddToClassList("inspector-subsection");
            var title = Label(L.T("#CLASSIC_PROP_SETTINGS"), "inspector-subsection-title");
            title.tooltip = L.T("#CLASSIC_PROP_SETTINGS_HELP"); settings.Add(title);

            var mantle = CompactInspectorField(new Toggle(L.T("#ALLOW_MANTLE")) { value = item.allowMantle });
            var fade = CompactInspectorField(new FloatField(L.T("#FADE_DISTANCE_APEX_U")) { value = item.fadeDistance, isDelayed = true });
            var realm = CompactInspectorField(new IntegerField(L.T("#REALM_ID")) { value = item.realmId, isDelayed = true });
            var client = CompactInspectorField(new Toggle(L.T("#CLIENT_SIDE_PROP")) { value = item.clientSide });
            settings.Add(mantle); settings.Add(fade); settings.Add(realm); settings.Add(client);

            mantle.RegisterValueChangedCallback(change => ChangeClassicProp(item.id, prop => prop.allowMantle = change.newValue));
            fade.RegisterValueChangedCallback(change =>
            {
                float value = float.IsFinite(change.newValue) ? Mathf.Max(-1f, change.newValue) : 50000f;
                if (!Mathf.Approximately(value, change.newValue)) fade.SetValueWithoutNotify(value);
                ChangeClassicProp(item.id, prop => prop.fadeDistance = value);
            });
            realm.RegisterValueChangedCallback(change =>
            {
                int value = Math.Max(-1, change.newValue);
                if (value != change.newValue) realm.SetValueWithoutNotify(value);
                ChangeClassicProp(item.id, prop => prop.realmId = value);
            });
            client.RegisterValueChangedCallback(change => ChangeClassicProp(item.id, prop => prop.clientSide = change.newValue));
            if (item.clientSide)
                settings.Add(Label(L.T("#CLIENT_PROP_CLASSIC_SETTINGS_IGNORED"), "inspector-inline-help"));
            section.Add(settings);
        }

        private void ChangeClassicProp(string id, Action<MapObject> change)
        {
            CommitInspectorEdit();
            session.Edit(document => change(document.objects.Find(candidate => candidate.id == id)));
            Refresh();
        }

        private void BuildScriptProperties(MapObject item, VisualElement section)
        {
            var properties = item.scriptProperties ?? new List<ScriptProperty>();
            var propertiesSection = new VisualElement { name = "script-properties" }; propertiesSection.AddToClassList("inspector-subsection");
            propertiesSection.tooltip = L.T("#CHOOSE_PROPERTY_FAMILY_COMPATIBLE_FIELD");
            var header = new VisualElement(); header.AddToClassList("script-properties-header");
            header.Add(Label(L.T("#SCRIPT_OPTIONS"), "script-properties-title"));
            header.Add(Label(properties.Count.ToString(CultureInfo.InvariantCulture), "script-properties-count"));
            propertiesSection.Add(header);

            var addCard = new VisualElement(); addCard.AddToClassList("script-property-add-card");
            var addRow = new VisualElement { name = "script-property-add" }; addRow.AddToClassList("script-property-add-controls");
            var addScope = new DropdownField(ScriptPropertyScopes, 1) { name = "script-property-add-scope", tooltip = L.T("#PROPERTY_FAMILY") };
            addScope.AddToClassList("script-property-scope");
            var addField = new DropdownField { name = "script-property-add-field", tooltip = L.T("#PROPERTY_FIELD") };
            addField.AddToClassList("script-property-field");
            void RefreshAddFields()
            {
                var choices = PropertyChoices(addScope.value.TrimStart('.'), item.clientSide);
                addField.choices = choices;
                addField.SetValueWithoutNotify(choices[0]);
            }
            addScope.RegisterValueChangedCallback(_ => RefreshAddFields());
            var add = Button("+", () =>
            {
                string selectedScope = addScope.value.TrimStart('.');
                var presets = PropertyPresets(selectedScope, item.clientSide);
                int selected = addField.choices.IndexOf(addField.value);
                var property = selected >= 0 && selected < presets.Count ? presets[selected].Create() : ManualProperty(selectedScope);
                ChangeScriptProperties(item.id, list => list.Add(property));
            });
            add.tooltip = L.T("#ADD_PROPERTY");
            add.AddToClassList("script-property-add-button"); add.AddToClassList("primary");
            addRow.Add(addScope); addRow.Add(addField); addRow.Add(add);
            addCard.Add(addRow); propertiesSection.Add(addCard); RefreshAddFields();

            for (int i = 0; i < properties.Count; i++)
            {
                int index = i;
                var property = properties[i];
                var card = new VisualElement(); card.AddToClassList("script-property-card");
                var row = new VisualElement(); row.AddToClassList("script-property-row");
                int scopeIndex = Math.Max(0, ScriptPropertyScopes.IndexOf("." + property.scope));
                var scope = new DropdownField(ScriptPropertyScopes, scopeIndex) { name = "script-property-scope", tooltip = L.T("#PROPERTY_FAMILY") };
                scope.AddToClassList("script-property-scope");
                var presets = PropertyPresets(property.scope, item.clientSide);
                var choices = PropertyChoices(property.scope, item.clientSide);
                int knownIndex = presets.FindIndex(p => p.Name == property.name);
                var field = new DropdownField(choices, knownIndex >= 0 ? knownIndex : choices.Count - 1) { name = "script-property-field", tooltip = L.T("#PROPERTY_FIELD") };
                field.AddToClassList("script-property-field");
                row.Add(scope); row.Add(field);
                var remove = Button("×", () => ChangeScriptProperties(item.id, list => list.RemoveAt(index)), "script-property-remove-button");
                remove.tooltip = L.T("#DELETE"); row.Add(remove);
                card.Add(row);
                var editorRow = new VisualElement(); editorRow.AddToClassList("script-property-editor-row");
                TextField name = null;
                if (knownIndex < 0)
                {
                    name = new TextField { value = property.name, isDelayed = true, tooltip = L.T("#FIELD_NAME") };
                    name.AddToClassList("script-property-name");
                    var nameControl = new VisualElement(); nameControl.AddToClassList("script-property-value-control"); nameControl.AddToClassList("script-property-name-control");
                    nameControl.Add(Label(L.T("#FIELD_NAME"), "script-property-control-label")); nameControl.Add(name); editorRow.Add(nameControl);
                    editorRow.Add(Label("=", "script-property-equals"));
                }
                var value = new TextField { value = property.value, isDelayed = true, tooltip = L.T("#SQUIRREL_VALUE") };
                value.AddToClassList("script-property-value");
                var valueControl = new VisualElement(); valueControl.AddToClassList("script-property-value-control"); valueControl.AddToClassList("script-property-value-entry-control");
                valueControl.Add(Label(L.T("#SQUIRREL_VALUE"), "script-property-control-label")); valueControl.Add(value); editorRow.Add(valueControl);
                card.Add(editorRow);
                scope.RegisterValueChangedCallback(e =>
                {
                    string selectedScope = e.newValue.TrimStart('.');
                    var replacement = PropertyPresets(selectedScope, item.clientSide).FirstOrDefault()?.Create() ?? ManualProperty(selectedScope);
                    ChangeScriptProperties(item.id, list => list[index] = replacement);
                });
                field.RegisterValueChangedCallback(e =>
                {
                    int selected = choices.IndexOf(e.newValue);
                    var replacement = selected >= 0 && selected < presets.Count ? presets[selected].Create() : ManualProperty(property.scope);
                    ChangeScriptProperties(item.id, list => list[index] = replacement);
                });
                if (name != null) name.RegisterValueChangedCallback(e => ChangeScriptProperties(item.id, list => list[index].name = e.newValue.Trim()));
                value.RegisterValueChangedCallback(e => ChangeScriptProperties(item.id, list => list[index].value = e.newValue.Trim()));
                propertiesSection.Add(card);
            }
            if (item.clientSide)
                propertiesSection.Add(Label(L.T("#CLIENT_E_FIELDS_MANUAL_ONLY"), "script-properties-help"));
            section.Add(propertiesSection);
        }

        private void ChangeScriptProperties(string id, Action<List<ScriptProperty>> change)
        {
            CommitInspectorEdit();
            session.Edit(doc =>
            {
                var target = doc.objects.Find(o => o.id == id);
                target.scriptProperties = target.scriptProperties ?? new List<ScriptProperty>();
                change(target.scriptProperties);
            });
            Refresh();
        }
