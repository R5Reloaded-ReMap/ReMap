        private static Vector3 OriginOffset(MapDocument document)
        {
            if (!document.originOffset.IsFinite || !ApexCoordinates.ContainsUnity(document.originOffset))
                throw new ArgumentException(L.T("#SCENE") + " : " + ApexCoordinates.LimitMessage);
            return WorldView.ToVector(document.originOffset);
        }

        private static bool HasOriginOffset(Vector3 value) => value.x != 0f || value.y != 0f || value.z != 0f;

        private static string Position(Float3 localPosition, Vector3 originOffset, bool symbolicOffset)
        {
            Vector3 local = WorldView.ToVector(localPosition);
            Vector3 game = local + originOffset;
            if (!ApexCoordinates.ContainsUnity(WorldView.ToData(game))) throw new ArgumentException(ApexCoordinates.LimitMessage);
            return Vector(ApexDisplay.Position(symbolicOffset ? local : game)) + (symbolicOffset ? " + originOffset" : "");
        }

        private static string Vector(Vector3 value) => "<" + Number(value.x) + ", " + Number(value.y) + ", " + Number(value.z) + ">";
        private static string ScriptString(string value) => "\"" + (value ?? "")
            .Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "\\n") + "\"";
        private static string Number(float value)
        {
            double rounded = Math.Round(value, 4, MidpointRounding.AwayFromZero);
            if (Math.Abs(rounded) < 0.00005) rounded = 0;
            return rounded.ToString("0.####", CultureInfo.InvariantCulture);
        }
        private static string FloatLiteral(float value)
        {
            string number = Number(value);
            return number.IndexOf('.') >= 0 ? number : number + ".0";
        }
        private static bool Nearly(float a, float b) => Math.Abs(a - b) <= Math.Max(0.0001f, Math.Max(Math.Abs(a), Math.Abs(b)) * 0.0001f);
    }

