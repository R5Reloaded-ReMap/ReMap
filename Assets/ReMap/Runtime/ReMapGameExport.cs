                card.Add(editorRow);
                scope.RegisterValueChangedCallback(e =>
                {
                    string selectedScope = e.newValue.TrimStart('.');
                    var replacement = PropertyPresets(selectedScope, item.clientSide).FirstOrDefault()?.Create() ?? ManualProperty(selectedScope);
                    ChangeScriptProperties(item.id, list => list[index] = replacement);
                });
                field.RegisterValueChangedCallback(e =>
                {
                    int selected = choices.IndexOf(e.newValue);
                    var replacement = selected >= 0 && selected < presets.Count ? presets[selected].Create() : ManualProperty(property.scope);
                    ChangeScriptProperties(item.id, list => list[index] = replacement);
                });
                if (name != null) name.RegisterValueChangedCallback(e => ChangeScriptProperties(item.id, list => list[index].name = e.newValue.Trim()));
                value.RegisterValueChangedCallback(e => ChangeScriptProperties(item.id, list => list[index].value = e.newValue.Trim()));
                propertiesSection.Add(card);
            }
            if (item.clientSide)
                propertiesSection.Add(Label(L.T("#CLIENT_E_FIELDS_MANUAL_ONLY"), "script-properties-help"));
            section.Add(propertiesSection);
        }

