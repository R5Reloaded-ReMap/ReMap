        public static string GenerateReset(string gameTarget = GameTargets.R5Reloaded)
        {
            gameTarget = GameTargets.Normalize(gameTarget);
            return RenderEdits(gameTarget, "Map source: reset script generated by the ReMap app.", ResetEdits(gameTarget));
        }

        public static string Generate(MapDocument document, IEnumerable<MapObject> worldObjects,
            IEnumerable<string> selectedRpaks = null)
        {
            if (document == null) throw new ArgumentNullException(nameof(document));
            return RenderEdits(GameTargets.Normalize(document.gameTarget), MapSourceDescription(document),
                BuildEdits(document, worldObjects, selectedRpaks));
        }

        internal static IReadOnlyList<ReMapGameScriptEdit> BuildEdits(MapDocument document,
            IEnumerable<MapObject> worldObjects, IEnumerable<string> selectedRpaks = null)
        {
            if (document == null) throw new ArgumentNullException(nameof(document));
            GameTargets.Normalize(document.gameTarget);
            string map = EditingMap(document);
            var world = (worldObjects ?? throw new ArgumentNullException(nameof(worldObjects))).Where(o => o != null).ToList();
            var objects = Prepare(world);
            var serverObjects = objects.Where(o => !o.clientSide).ToList();
            var clientObjects = objects.Where(o => o.clientSide).ToList();
            var models = objects.Select(Model).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
            models.AddRange(world.Where(o => o.customType == "door")
                .Select(o => ReMapDoorProfiles.Find(o.doorType).ModelPath)
                .Where(model => !models.Contains(model, StringComparer.OrdinalIgnoreCase)));
            if (world.Any(o => o.customType == "loot-bin") &&
                !models.Contains(ReMapApp.LootBinModelPath, StringComparer.OrdinalIgnoreCase))
                models.Add(ReMapApp.LootBinModelPath);
            if (world.Any(o => o.customType == "jump-pad") &&
                !models.Contains(ReMapApp.JumpPadModelPath, StringComparer.OrdinalIgnoreCase))
                models.Add(ReMapApp.JumpPadModelPath);
            if (world.Any(o => o.customType == "spawn-point") &&
                !models.Contains(ReMapApp.SpawnPointModelPath, StringComparer.OrdinalIgnoreCase))
                models.Add(ReMapApp.SpawnPointModelPath);
            if (world.Any(o => o.customType == "jump-tower"))
            {
                if (!models.Contains(ReMapApp.JumpTowerBaseModelPath, StringComparer.OrdinalIgnoreCase))
                    models.Add(ReMapApp.JumpTowerBaseModelPath);
                if (!models.Contains(ReMapApp.JumpTowerBalloonModelPath, StringComparer.OrdinalIgnoreCase))
                    models.Add(ReMapApp.JumpTowerBalloonModelPath);
            }
            Vector3 originOffset = OriginOffset(document);
            bool useOriginOffset = HasOriginOffset(originOffset);
            var shared = new StringBuilder();
            AppendRpakLoadRequests(shared, AdditionalRpaks(map, selectedRpaks));
            foreach (string model in models) shared.Append("\tPrecacheModel( $\"").Append(model).AppendLine("\" )");

            var server = new StringBuilder();
            server.Append("\tif ( GetMapName() != \"").Append(map).AppendLine("\" )");
            server.AppendLine("\t\treturn");
            server.AppendLine();
            AppendClear(server);
            if (useOriginOffset)
            {
                server.AppendLine();
                server.Append("\tvector originOffset = ").Append(Vector(ApexDisplay.Position(originOffset))).AppendLine();
            }
            if (serverObjects.Count > 0)
            {
                server.AppendLine();
                server.AppendLine("\t// Props");
                server.AppendLine("\tentity ent");
            }
            for (int i = 0; i < serverObjects.Count; i++) AppendObject(server, serverObjects[i], originOffset, useOriginOffset);
            AppendDoors(server, world, false, originOffset, useOriginOffset);
            AppendLootBins(server, world, false, originOffset, useOriginOffset);
            AppendJumpPads(server, world, false, originOffset, useOriginOffset);
            AppendSpawnPoints(server, world, false, originOffset, useOriginOffset);
            AppendTriggers(server, world, false, originOffset, useOriginOffset);
            AppendJumpTowers(server, world, false, originOffset, useOriginOffset);
            AppendCurvedZiplines(server, world, false, originOffset, useOriginOffset);
            AppendZiplines(server, world, false, originOffset, useOriginOffset);

            var client = new StringBuilder();
            client.Append("\tif ( GetMapName() != \"").Append(map).AppendLine("\" )");
            client.AppendLine("\t\treturn");
            client.AppendLine();
            AppendClear(client);
            if (useOriginOffset)
            {
                client.AppendLine();
                client.Append("\tvector originOffset = ").Append(Vector(ApexDisplay.Position(originOffset))).AppendLine();
            }
            if (clientObjects.Count > 0)
            {
                client.AppendLine();
                client.AppendLine("\t// Client-side props");
                client.AppendLine("\tentity ent");
            }
            foreach (var item in clientObjects)
            {
                client.Append("\tent = ReMap_CreateClientProp( $\"").Append(Model(item)).Append("\", ")
                    .Append(Position(item.position, originOffset, useOriginOffset)).Append(", ")
                    .Append(Vector(ApexDisplay.Angles(WorldView.ToVector(item.rotation)))).Append(", ")
                    .Append(Number(item.scale.x)).AppendLine(" )");
                foreach (var property in item.scriptProperties ?? new List<ScriptProperty>())
                    AppendProperty(client, "ent", property, "\t", true);
            }
            return new[]
            {
                new ReMapGameScriptEdit(SharedFileName, "Sh_ReMap_PrecacheMap", shared.ToString().TrimEnd()),
                new ReMapGameScriptEdit(ServerMapFileName, "Sv_ReMap_LoadMap", server.ToString().TrimEnd()),
                new ReMapGameScriptEdit(ClientMapFileName, "Cl_ReMap_LoadMap", client.ToString().TrimEnd())
            };
        }

        internal static IReadOnlyList<ReMapGameScriptEdit> ResetEdits(string gameTarget)
        {
            GameTargets.Normalize(gameTarget);
            return new[]
            {
                new ReMapGameScriptEdit(SharedFileName, "Sh_ReMap_PrecacheMap", "\tPrecacheModel( $\"mdl/dev/empty.rmdl\" )"),
                new ReMapGameScriptEdit(ServerMapFileName, "Sv_ReMap_LoadMap", ""),
                new ReMapGameScriptEdit(ClientMapFileName, "Cl_ReMap_LoadMap", "")
            };
        }

        private static string RenderEdits(string gameTarget, string sourceDescription, IReadOnlyList<ReMapGameScriptEdit> edits)
        {
            var code = new StringBuilder();
            AppendGeneratedHeader(code, gameTarget, sourceDescription);
            foreach (var edit in edits)
            {
                code.Append("// File: ").Append(DirectoryName).Append('/').AppendLine(edit.FileName);
                code.Append("global function ").AppendLine(edit.FunctionName);
                code.AppendLine();
                code.Append("void function ").Append(edit.FunctionName).Append("()");
                if (edit.Body.Length == 0) code.AppendLine(" {}");
                else
                {
                    code.AppendLine();
                    code.AppendLine("{");
                    code.AppendLine(edit.Body);
                    code.AppendLine("}");
                }
                code.AppendLine();
            }
            return code.ToString();
        }

        public static string GenerateLiveCommands(MapDocument document, IEnumerable<MapObject> worldObjects,
            IEnumerable<string> selectedRpaks = null)
        {
            EditingMap(document);
            string gameTarget = GameTargets.Normalize(document.gameTarget);
            var world = (worldObjects ?? throw new ArgumentNullException(nameof(worldObjects))).Where(o => o != null).ToList();
            var objects = Prepare(world).Where(o => !o.clientSide).ToList();
            Vector3 originOffset = OriginOffset(document);
            var result = new StringBuilder();
            foreach (string rpak in AdditionalRpaks(EditingMap(document), selectedRpaks))
                result.Append("pak_requestload ").AppendLine(rpak);
            result.Append("script Sh_ReMap_Clear()\n");
            for (int i = 0; i < objects.Count; i++)
                result.Append("script ").Append(CreateExpression(objects[i], originOffset, false)).AppendLine();
            AppendDoors(result, world, true, originOffset, false);
            AppendLootBins(result, world, true, originOffset, false);
            AppendJumpPads(result, world, true, originOffset, false);
            AppendSpawnPoints(result, world, true, originOffset, false);
            AppendJumpTowers(result, world, true, originOffset, false);
            AppendCurvedZiplines(result, world, true, originOffset, false);
            AppendZiplines(result, world, true, originOffset, false);
            return result.ToString();
        }

        internal static string[] AdditionalRpaks(string editingMap,
            IEnumerable<string> selectedRpaks)
        {
            string prefix = editingMap + ".rpak";
            string clientPerm = editingMap + "_client_perm.rpak";
            string clientTemp = editingMap + "_client_temp.rpak";
            var result = new List<string>();
            foreach (string source in selectedRpaks ?? Array.Empty<string>())
            {
                string rpak = (source ?? "").Trim();
                if (!Regex.IsMatch(rpak, @"^[A-Za-z0-9_()\-]+\.rpak$", RegexOptions.CultureInvariant))
                    throw new ArgumentException(L.F("#INVALID_RPAK_FILE_NAME_ARG0", rpak));
                if (string.Equals(rpak, prefix, StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(rpak, clientPerm, StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(rpak, clientTemp, StringComparison.OrdinalIgnoreCase)) continue;
                if (!result.Contains(rpak, StringComparer.OrdinalIgnoreCase)) result.Add(rpak);
            }
            return result.ToArray();
        }

        private static void AppendRpakLoadRequests(StringBuilder code, IEnumerable<string> rpaks)
        {
            string[] archives = (rpaks ?? Array.Empty<string>()).ToArray();
            if (archives.Length == 0) return;
            code.AppendLine("#if SERVER");
            foreach (string rpak in archives)
                code.Append("\tServerCommand( \"pak_requestload ").Append(rpak).AppendLine("\" )");
            code.AppendLine("#elseif CLIENT");
            foreach (string rpak in archives)
                code.Append("\tClientCommand( \"pak_requestload ").Append(rpak).AppendLine("\" )");
            code.AppendLine("#endif");
            code.AppendLine();
        }

        private static void AppendClear(StringBuilder code)
        {
            code.AppendLine("\tSh_ReMap_Clear()");
        }

        private static string MapSourceDescription(MapDocument document)
        {
            string projectName = (document?.name ?? "").Replace('\r', ' ').Replace('\n', ' ').Trim();
            return projectName.Length == 0
                ? "Map source: current project in the ReMap app."
                : "Map source: ReMap project \"" + projectName + "\".";
        }

        private static void AppendGeneratedHeader(StringBuilder code, string gameTarget, string sourceDescription)
        {
            code.Append("// Generated by ReMap for ").Append(GameTargets.DisplayName(gameTarget)).AppendLine(".");
            code.Append("// ").AppendLine(sourceDescription);
            code.AppendLine("// ReMap only replaces the named function bodies in the installed scripts.");
            code.AppendLine("// Original ReMap by Zee (@AyeZeeBB / zee_x64) and Julefox (@Julefox_ / julefox).");
            code.AppendLine("// Standalone ReMap rewrite created and maintained by Julefox.");
            code.AppendLine("// Made with love for the Apex modding community. <3");
            code.AppendLine("// Built on the Apex modding foundation created by Mauler125: https://github.com/Mauler125/r5sdk");
            code.AppendLine();
        }

        private static string EditingMap(MapDocument document)
        {
            if (document == null) throw new ArgumentNullException(nameof(document));
            string map = (document.editingMap ?? "").Trim();
            if (!map.StartsWith("mp_", StringComparison.Ordinal) || map.Length > 128 || map.Any(c =>
                    !((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_')))
                throw new ArgumentException(L.T("#SELECT_EDITED_APEX_MAP_BUILDING"));
            return map;
        }

        private static List<MapObject> Prepare(IEnumerable<MapObject> source)
        {
            var objects = (source ?? throw new ArgumentNullException(nameof(source))).Where(o => o != null && !o.isGroup && !o.disabled && string.IsNullOrEmpty(o.customType)).ToList();
            foreach (var item in objects)
            {
                Model(item);
                if (!Nearly(item.scale.x, item.scale.y) || !Nearly(item.scale.x, item.scale.z))
                    throw new ArgumentException(L.F("#ARG0_APEX_PROPS_SUPPORT_UNIFORM", item.displayName));
            }
            return objects;
        }

        private static string Model(MapObject item)
        {
            string model = (item.gameModelPath ?? "").Trim().Replace('\\', '/');
            if (!model.StartsWith("mdl/", StringComparison.OrdinalIgnoreCase) || !model.EndsWith(".rmdl", StringComparison.OrdinalIgnoreCase) ||
                model.IndexOfAny(new[] { '"', '\r', '\n' }) >= 0)
                throw new ArgumentException(L.F("#ARG0_NO_VALID_APEX_MODEL", item.displayName));
            return model;
        }

        private static void AppendObject(StringBuilder code, MapObject item, Vector3 originOffset, bool symbolicOffset)
        {
            const string variable = "ent";
            code.Append('\t').Append(variable).Append(" = ").Append(CreateExpression(item, originOffset, symbolicOffset)).AppendLine();
            foreach (var property in item.scriptProperties ?? new List<ScriptProperty>())
                AppendProperty(code, variable, property, "\t", true);
        }

        private static void AppendProperty(StringBuilder code, string variable, ScriptProperty property, string prefix, bool lineBreak = false)
        {
            code.Append(prefix).Append(variable).Append('.');
            if (!string.IsNullOrEmpty(property.scope)) code.Append(property.scope).Append('.');
            code.Append(property.name).Append(property.scope == "s" ? " <- " : " = ").Append(property.value);
            if (lineBreak) code.AppendLine();
        }

        private static string CreateExpression(MapObject item, Vector3 originOffset, bool symbolicOffset)
        {
            Vector3 angles = ApexDisplay.Angles(WorldView.ToVector(item.rotation));
            string common = "$\"" + Model(item) + "\", " + Position(item.position, originOffset, symbolicOffset) + ", " + Vector(angles);
            return "ReMap_CreateProp( " + common + ", " + (item.allowMantle ? "true" : "false") +
                ", " + Number(item.fadeDistance) + ", " + item.realmId.ToString(CultureInfo.InvariantCulture) +
                ", " + Number(item.scale.x) + " )";
        }

        private static void AppendZiplines(StringBuilder code, List<MapObject> world, bool live, Vector3 originOffset, bool symbolicOffset)
        {
            var byId = world.ToDictionary(o => o.id);
            var ziplines = world.Where(o => o.customType == "zipline").ToList();
            if (!live && ziplines.Count > 0) { code.AppendLine(); code.AppendLine("\t// Ziplines"); }
            foreach (var zipline in ziplines)
            {
                if (!byId.TryGetValue(zipline.ziplineStartId, out var start) || !byId.TryGetValue(zipline.ziplineEndId, out var end))
                    throw new ArgumentException(L.F("#ARG0_ZIPLINE_ENDPOINTS_MISSING", zipline.displayName));
                bool vertical = zipline.ziplineMode == "vertical";
                string startProfile = ReMapZiplineProfiles.Find(start.customProfile).ScriptConstant;
                string endProfile = ReMapZiplineProfiles.Find(end.customProfile).ScriptConstant;
                string expression = "ReMap_CreateZipline( " + Position(start.position, originOffset, symbolicOffset) + ", " + Vector(ApexDisplay.Angles(WorldView.ToVector(start.rotation))) +
                    ", " + Position(end.position, originOffset, symbolicOffset) + ", " + Vector(ApexDisplay.Angles(WorldView.ToVector(end.rotation))) + ", " +
                    startProfile + ", " + endProfile +
                    ", " + (vertical ? "true" : "false") + ", " + Number(zipline.ziplineWidth) + ", " + Number(zipline.ziplineSpeed) +
                    ", " + Number(start.ziplineArmHeight) + ", " + Number(end.ziplineArmHeight) +
                    ", " + (zipline.ziplinePushOffInDirectionX ? "true" : "false") + ", " + Number(zipline.ziplineLengthScale) +
                    ", " + Number(zipline.ziplinePushOffAngle) + ", " + Number(zipline.ziplineFadeDistance) +
                    ", " + Number(zipline.ziplineScale) + ", " + (zipline.ziplinePreserveVelocity ? "true" : "false") +
                    ", " + (zipline.ziplineDropToBottom ? "true" : "false") + ", " + Number(zipline.ziplineAutoDetachStart) +
                    ", " + Number(zipline.ziplineAutoDetachEnd) + ", " + (zipline.ziplineRestPoint ? "true" : "false") +
                    ", " + (zipline.ziplineDetachEndOnSpawn ? "true" : "false") +
                    ", " + (zipline.ziplineDetachEndOnUse ? "true" : "false") + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendDoors(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            var doors = world.Where(o => o.customType == "door").ToList();
            if (!live && doors.Count > 0) { code.AppendLine(); code.AppendLine("\t// Doors"); }
            foreach (var door in doors)
            {
                var profile = ReMapDoorProfiles.Find(door.doorType);
                string expression = "ReMap_CreateDoor( " +
                    Position(door.position, originOffset, symbolicOffset) + ", " +
                    Vector(ApexDisplay.Angles(WorldView.ToVector(door.rotation))) + ", " +
                    profile.ScriptConstant + ", " +
                    (door.doorGold && profile.SupportsGold ? "true" : "false") + ", " +
                    (door.doorSpawnOpen ? "true" : "false") + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendCurvedZiplines(StringBuilder code, List<MapObject> world, bool live,
            Vector3 originOffset, bool symbolicOffset)
        {
            var ziplines = world.Where(o => o.customType == "curved-zipline").ToList();
            if (!live && ziplines.Count > 0) { code.AppendLine(); code.AppendLine("\t// Curved ziplines"); }
            foreach (var zipline in ziplines)
            {
                var points = world.Where(o => o.parentId == zipline.id &&
                    o.customType == "curved-zipline-point")
                    .OrderBy(o => int.TryParse(o.customRole, out int index) ? index : int.MaxValue)
                    .ToList();
                if (points.Count < 2)
                    throw new ArgumentException(L.F("#ARG0_CURVED_ZIPLINE_POINTS_MISSING", zipline.displayName));
                string pointArray = "[ " + string.Join(", ", points.Select(point =>
                    Position(point.position, originOffset, symbolicOffset))) + " ]";
                string profileArray = "[ " + string.Join(", ", points.Select(point =>
                    ReMapZiplineProfiles.Find(point.customProfile).ScriptConstant)) + " ]";
                string angleArray = "[ " + string.Join(", ", points.Select(point =>
                    Vector(ApexDisplay.Angles(WorldView.ToVector(point.rotation))))) + " ]";
                string heightArray = "[ " + string.Join(", ", points.Select(point =>
                    Number(point.ziplineArmHeight))) + " ]";
                string expression = "ReMap_CreateCurvedZipline( " + pointArray + ", " +
                    zipline.curvedZiplineSegments.ToString(CultureInfo.InvariantCulture) + ", " +
                    profileArray + ", " + angleArray + ", " + heightArray + ", " +
                    Number(zipline.ziplineWidth) + ", " + Number(zipline.ziplineSpeed) + " )";
                code.Append(live ? "script " : "\t").Append(expression).AppendLine();
            }
        }

        private static void AppendLootBins(StringBuilder code, List<MapObject> world, bool live,
