                var value = new TextField { value = property.value, isDelayed = true, tooltip = L.T("#SQUIRREL_VALUE") };
                value.AddToClassList("script-property-value");
                var valueControl = new VisualElement(); valueControl.AddToClassList("script-property-value-control"); valueControl.AddToClassList("script-property-value-entry-control");
