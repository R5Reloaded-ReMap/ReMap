        public static string EnsureInstalled(string platformDirectory, string gameTarget)
        {
            gameTarget = GameTargets.Normalize(gameTarget);
            string platform = (platformDirectory ?? "").Trim();
            if (platform.Length == 0) throw new DirectoryNotFoundException(L.T("#CONFIGURE_PLATFORM_FOLDER_SETTINGS_FIRST"));
            string scripts = Path.Combine(Path.GetFullPath(platform), "scripts", "vscripts");
            string remap = Path.Combine(scripts, ReMapGameScript.DirectoryName);
            var allFiles = ServerFileNames.Concat(ClientFileNames).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
            foreach (string fileName in allFiles)
            {
                string entry = ReMapGameScript.DirectoryName + "/" + fileName;
                string runtime = Path.Combine(remap, fileName);
                if (!File.Exists(runtime))
                    throw new FileNotFoundException(L.F("#ARG0_PLATFORM_CONTAIN_REQUIRED_ARG1", GameTargets.DisplayName(gameTarget), entry), runtime);
            }

            string initName = gameTarget == GameTargets.R5Flowstate ? "_sh_init.gnut" : "sh_init.gnut";
            string init = Path.Combine(scripts, initName);
            if (!File.Exists(init) || !File.ReadAllText(init).Contains("Sh_ReMap_Init()"))
                throw new InvalidDataException(L.F("#REMAP_INIT_MISSING", initName));

            return remap;
        }

