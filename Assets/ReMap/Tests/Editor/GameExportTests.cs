        }

        [Test]
        public void ClassicPropSettingsUseLegacyDefaultsAndSurviveSaveMigration()
        {
            var item = new MapObject();
            Assert.That(item.allowMantle, Is.True);
            Assert.That(item.fadeDistance, Is.EqualTo(50000f));
            Assert.That(item.realmId, Is.EqualTo(-1));
            Assert.That(item.clientSide, Is.False);

            string legacy = "{\"schemaVersion\":1,\"coordinateSystem\":\"unity-y-up-meters\",\"objects\":[{" +
                "\"id\":\"" + item.id + "\",\"assetId\":\"apex:crate\",\"displayName\":\"Crate\"}]}";
            var migrated = new UnityMapCodec().Decode(legacy);
            Assert.That(migrated.objects[0].allowMantle, Is.True);
            Assert.That(migrated.objects[0].fadeDistance, Is.EqualTo(50000f));
            Assert.That(migrated.objects[0].realmId, Is.EqualTo(-1));

            item.allowMantle = false; item.fadeDistance = 12345f; item.realmId = 7; item.clientSide = true;
            var document = new MapDocument(); document.objects.Add(item);
            var roundTrip = new UnityMapCodec().Decode(new UnityMapCodec().Encode(document));
            Assert.That(roundTrip.objects[0].allowMantle, Is.False);
            Assert.That(roundTrip.objects[0].fadeDistance, Is.EqualTo(12345f));
            Assert.That(roundTrip.objects[0].realmId, Is.EqualTo(7));
            Assert.That(roundTrip.objects[0].clientSide, Is.True);
        }

