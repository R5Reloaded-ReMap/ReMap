        [Test]
        public void GeneratesApexPropAndScriptProperties()
        {
            var document = new MapDocument { name = "Test map", gameTarget = GameTargets.R5Flowstate, editingMap = "mp_rr_desertlands_hu" };
            var item = new MapObject
            {
                displayName = "Crate",
                assetId = "apex:crate",
                gameModelPath = "mdl/props/crate.rmdl",
                position = ApexCoordinates.ToUnity(new Float3(256, -128, 64)),
                rotation = WorldView.ToData(ApexDisplay.UnityAngles(new Vector3(10, 20, 30))),
                scale = new Float3(2, 2, 2)
            };
            item.scriptProperties.Add(new ScriptProperty { scope = "kv", name = "solid", value = "6" });
            item.scriptProperties.Add(new ScriptProperty { scope = "s", name = "remapTag", value = "\"cover\"" });
            item.scriptProperties.Add(new ScriptProperty { scope = "", name = "customField", value = "42" });
            document.objects.Add(item);

            string code = ReMapGameScript.Generate(document, new[] { item });

            StringAssert.StartsWith("// Generated by ReMap for R5Flowstate.\n// Map source: ReMap project \"Test map\".", code.Replace("\r\n", "\n"));
            StringAssert.Contains("PrecacheModel( $\"mdl/props/crate.rmdl\" )", code);
            StringAssert.Contains("if ( GetMapName() != \"mp_rr_desertlands_hu\" )", code);
            StringAssert.Contains("entity ent", code);
            StringAssert.Contains("entity ent\n\tent = ReMap_CreateProp", code.Replace("\r\n", "\n"));
            StringAssert.Contains("ent = ReMap_CreateProp( $\"mdl/props/crate.rmdl\", <256, -128, 64>, <10, 20, 30>, true, 50000, -1, 2 )", code);
            StringAssert.Contains("ent.kv.solid = 6", code);
            StringAssert.Contains("ent.s.remapTag <- \"cover\"", code);
            StringAssert.Contains("ent.customField = 42", code);
            StringAssert.DoesNotContain("ent..customField", code);
            StringAssert.DoesNotContain("originOffset", code);
            string normalizedCode = code.Replace("\r\n", "\n");
            StringAssert.Contains("void function Sh_ReMap_PrecacheMap()\n{\n", normalizedCode);
            StringAssert.Contains("void function Sv_ReMap_LoadMap()\n{\n", normalizedCode);
            StringAssert.Contains("void function Cl_ReMap_LoadMap()\n{\n", normalizedCode);

            string live = ReMapGameScript.GenerateLiveCommands(document, new[] { item });
            StringAssert.StartsWith("script Sh_ReMap_Clear()", live);
            StringAssert.DoesNotContain("script ReMap_ClearZiplines()", live);
            StringAssert.Contains("script ReMap_CreateProp( $\"mdl/props/crate.rmdl\", <256, -128, 64>, <10, 20, 30>, true, 50000, -1, 2 )", live);
            StringAssert.DoesNotContain("entity remapLive", live);
            StringAssert.DoesNotContain("remapLive", live);
            StringAssert.DoesNotContain("script_server", live);
            StringAssert.DoesNotContain("originOffset", live);
        }

