        [Test]
        public void GeneratedPublicFunctionsUseTheReMapPrefix()
        {
            string root = System.IO.Path.GetFullPath(System.IO.Path.Combine(Application.dataPath, "..", "scripts", "vscripts"));
            string[] variants = { "remap_r5r", "remap_r5f" };
            foreach (string variant in variants)
            {
                string variantRoot = System.IO.Path.Combine(root, variant);
                Assert.That(System.IO.Directory.GetFiles(variantRoot, "*.gnut"), Is.Empty, variant + " contains an unexpected global script.");
                foreach (string path in System.IO.Directory.GetFiles(variantRoot, "*.nut"))
                {
                    string code = System.IO.File.ReadAllText(path);
                    StringAssert.StartsWith("// Generated by ReMap for ", code, path);
                    StringAssert.Contains("// Source code: https://github.com/ReMap", code, path);
                    StringAssert.DoesNotContain("preserved from the source", code, path);
                    StringAssert.DoesNotContain("scripts/vscripts/source", code, path);
                    foreach (System.Text.RegularExpressions.Match match in System.Text.RegularExpressions.Regex.Matches(code, @"(?m)^global function\s+(\w+)"))
                        StringAssert.IsMatch(@"^(?:ReMap_|Sh_ReMap_|Sv_ReMap_|Cl_ReMap_)", match.Groups[1].Value, path);
                }
            }
        }
